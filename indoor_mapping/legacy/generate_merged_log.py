# generate_merged_log.py
import math

def generate_log_file(original_scan_file, output_log_file, robot_positions):
    """
    Reads a static scan file and generates a merged SLAM log file
    by simulating that scan from multiple robot positions.
    """
    print(f"Reading base scan data from {original_scan_file}...")
    
    try:
        with open(original_scan_file, 'r', encoding='utf-8') as f:
            base_scan_data = f.readlines()
        print(f"Base scan template has {len(base_scan_data)} lines.")
    except FileNotFoundError:
        print(f"Error: Base file {original_scan_file} not found.")
        return

    total_lines = 0
    
    with open(output_log_file, 'w', encoding='utf-8') as out_f:
        out_f.write("# SLAM Log File Generated by generate_merged_log.py\n")
        out_f.write(f"# Simulating {len(robot_positions)} robot positions.\n")
        
        # Iterate over each position the robot stops at
        for (robot_x, robot_y) in robot_positions:
            print(f"Simulating scan at position ({robot_x}, {robot_y})...")
            
            # Read the 360-degree scan data for this position
            for line in base_scan_data:
                line = line.strip()
                if line.startswith('#') or not line:
                    continue
                try:
                    parts = line.split(',')
                    if len(parts) == 2:
                        angle_deg = float(parts[0])
                        distance_cm = float(parts[1])
                        angle_rad = math.radians(angle_deg)
                        
                        # Write the merged log line
                        # Format: robot_x, robot_y, angle, distance
                        out_f.write(f"{robot_x},{robot_y},{angle_rad},{distance_cm}\n")
                        total_lines += 1
                except ValueError:
                    pass # Skip bad lines

    print(f"Successfully generated {output_log_file} with {total_lines} data points.")

